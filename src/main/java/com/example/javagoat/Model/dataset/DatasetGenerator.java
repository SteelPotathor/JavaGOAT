/**
 * Builds data/seed/profiles.json: the hand-written showcase profiles (data/showcase-profiles.json) followed by
 * generated profiles. The generation is deterministic for a given seed and reference date.
 * <p>
 * Usage, from the project root: {@code mvnw compile exec:java} or, with options,
 * {@code mvnw compile exec:java -Dexec.args="--count=500 --seed=2026 --reference-date=2026-11-10"}.
 * <p>
 * Rules (see data/README.md): realistic distributions (height by sex, IQ ~ N(100, 15), lifestyles),
 * mostly heterosexual preferences, preferences derived from the person's own profile (age range around
 * their age, non-smokers who avoid smokers, vegans who prefer vegetarians...), passions drawn from one or
 * two "personas" so that people share interests, and a past match history for about 20% of the people.
 */
public final class DatasetGenerator {

    private final Random random;
    private final LocalDate referenceDate;
    private final Set<String> usedNames = new HashSet<>();

    DatasetGenerator(long seed, LocalDate referenceDate) {
        this.random = new Random(seed);
        this.referenceDate = referenceDate;
    }

    public static void main(String[] args) throws IOException {
        Map<String, String> options = parseArgs(args);
        int count = Integer.parseInt(options.getOrDefault("count", "500"));
        long seed = Long.parseLong(options.getOrDefault("seed", "2026"));
        LocalDate referenceDate = LocalDate.parse(options.getOrDefault("reference-date", LocalDate.now().toString()));
        Path showcase = Path.of(options.getOrDefault("showcase", "data/showcase-profiles.json"));
        Path output = Path.of(options.getOrDefault("output", "data/seed/profiles.json"));

        LinkedHashMap<Integer, Profile> profiles = Files.exists(showcase) ? ProfileStore.read(showcase) : new LinkedHashMap<>();
        System.out.println("[generator] " + profiles.size() + " showcase profiles read from " + showcase);

        DatasetGenerator generator = new DatasetGenerator(seed, referenceDate);
        profiles.values().forEach(p -> generator.usedNames.add(p.getIdentity().getFirstname() + " " + p.getIdentity().getLastname()));
        int firstGeneratedId = profiles.keySet().stream().mapToInt(Integer::intValue).max().orElse(0) + 1;
        List<Profile> generated = new ArrayList<>();
        for (int id = firstGeneratedId; profiles.size() < count; id++) {
            Profile profile = generator.generate(id);
            profiles.put(id, profile);
            generated.add(profile);
        }
        int matches = generator.addMatchHistory(generated, new Matcher(MatchingSettings.defaults()));

        String comment = "Generated by DatasetGenerator (seed=" + seed + ", count=" + count + ", reference date="
                + referenceDate + ") from " + showcase.getFileName() + ". Regenerate with: mvnw compile exec:java";
        ProfileStore.write(output, profiles.values(), comment);
        System.out.println("[generator] " + profiles.size() + " profiles (" + generated.size() + " generated, "
                + matches + " past matches) written to " + output.toAbsolutePath());
    }

    private static Map<String, String> parseArgs(String[] args) {
        Map<String, String> options = new HashMap<>();
        for (String arg : args) {
            if (!arg.startsWith("--") || !arg.contains("=")) {
                throw new IllegalArgumentException("Expected --name=value, got: " + arg);
            }
            options.put(arg.substring(2, arg.indexOf('=')), arg.substring(arg.indexOf('=') + 1));
        }
        return options;
    }

    // ================================================================== one profile

    Profile generate(int id) {
        Biology.sex sex = random.nextBoolean() ? Biology.sex.FEMALE : Biology.sex.MALE;
        boolean female = sex == Biology.sex.FEMALE;
        int age = clamp(normal(36, 11), 19, 75);
        String[] name = uniqueName(sex);
        Identity identity = new Identity(age, sex, pick(Biology.ethnicity.values()), clamp(normal(100, 15), 60, 145), name[1], name[0], id);

        PhysicalAttributes physical = new PhysicalAttributes(
                clamp(female ? normal(165, 7) : normal(178, 7), 145, 205),
                weighted(PhysicalAttributes.hairColor.values(), 24, 8, 40, 28),        // BLONDE RED BRUNETTE BLACK
                weighted(PhysicalAttributes.hairType.values(), 50, 33, 17),            // STRAIGHT WAVY CURLY
                female ? weighted(PhysicalAttributes.hairLength.values(), 50, 32, 18)  // LONG HALF_LONG SHORT
                        : weighted(PhysicalAttributes.hairLength.values(), 8, 22, 70));

        LifeStyle.athlete athlete = weighted(LifeStyle.athlete.values(), 32, 48, 20);   // SPORTY SEDENTARY LAZY
        LifeStyle.bodyBuild bodyBuild = switch (athlete) {                             // SKINNY MEDIUM OVERWEIGHT
            case SPORTY -> weighted(LifeStyle.bodyBuild.values(), 40, 55, 5);
            case SEDENTARY -> weighted(LifeStyle.bodyBuild.values(), 30, 50, 20);
            case LAZY -> weighted(LifeStyle.bodyBuild.values(), 20, 40, 40);
        };
        LifeStyle lifeStyle = new LifeStyle(
                weighted(LifeStyle.smoker.values(), 62, 18, 10, 10),                    // NEVER OCCASIONNALY REGULARLY DAILY
                athlete,
                weighted(LifeStyle.feed.values(), 6, 14, 58, 22),                       // VEGAN VEGETARIAN OMNIVORE FLEXIVORE
                bodyBuild,
                weighted(LifeStyle.religion.values(), 12, 30, 4, 5, 4, 7, 38),          // MUSLIM CHRISTIAN JEWISH BUDDHIST HINDUIST OTHER ATHEIST
                weighted(LifeStyle.alcohol.values(), 18, 50, 26, 6));                   // NEVER OCCASIONNALY REGULARLY DAILY

        Passion passion = passions(athlete);
        Profile profile = new Profile(identity, physical, lifeStyle, new Preferences(), passion, ImageLoader.DEFAULT_PROFILE_IMAGE);
        profile.setPreferences(preferences(profile));
        return profile;
    }

    private String[] uniqueName(Biology.sex sex) {
        NameGenerator names = new NameGenerator(sex, random);
        for (int attempt = 0; attempt < 1000; attempt++) {
            String[] name = names.getRandomName();
            if (usedNames.add(name[0] + " " + name[1])) {
                return name;
            }
        }
        throw new IllegalStateException("Not enough distinct names");
    }

    // ================================================================== passions

    private enum Persona {
        GAMER, SPORTY, ARTSY, INTELLECTUAL, HOMEBODY, TRAVELER
    }

    private static final Map<Persona, List<Passion.miscellaneous>> PERSONA_PASSIONS = Map.of(
            Persona.GAMER, misc("ANIME", "MANGA", "NETFLIX", "PROGRAMMING", "COSPLAY", "MOVIES", "GRINDING", "SLEEP"),
            Persona.SPORTY, misc("RUNNING", "GYM", "BIKE", "BASKET", "TENNIS", "SOCCER", "MARTIAL_ARTS", "CLIMBING", "DIVING", "YOGA"),
            Persona.ARTSY, misc("PAINTING", "MUSIC", "PHOTOGRAPHY", "THEATER", "WRITING", "DANCING", "LITERATURE", "DECORATIONS", "MODE"),
            Persona.INTELLECTUAL, misc("HISTORY", "GEOGRAPHY", "PHILOSOPHY", "PSYCHOLOGY", "SCIENCES", "CHESS", "LITERATURE", "PROGRAMMING"),
            Persona.HOMEBODY, misc("COOKING", "GARDENING", "NETFLIX", "MOVIES", "ANIMALS", "DECORATIONS", "SLEEP", "PLAYING_WITH_KIDS"),
            Persona.TRAVELER, misc("TRAVELING", "VACATIONS", "PHOTOGRAPHY", "DIVING", "GEOGRAPHY", "SPIRITUALITY", "VLOGGING", "COOKING"));

    /** Passions that are never generated (they stay available in the forms). */
    private static final Set<Passion.miscellaneous> NOT_GENERATED = EnumSet.copyOf(misc("PORN", "NUDISM", "FURRIES"));

    private static final List<List<Passion.video_games>> GAME_FAMILIES = List.of(
            games("LEAGUE_OF_LEGENDS", "VALORANT", "CS_GO", "DOTA_2", "APEX_LEGENDS", "ROCKET_LEAGUE", "STREET_FIGHTER", "CALL_OF_DUTY", "FORTNITE", "PUBG"),
            games("MINECRAFT", "TERRARIA", "VALHEIM", "ARK", "RUST", "GENSHIN_IMPACT", "SEA_OF_THIEVES"),
            games("JACKBOX_PARTY", "AMOGUS", "FALL_GUYS", "CRAB_GAME", "SUPER_SMASH_BROS", "BRAWLHALLA", "DIVINE_KNOCKOUT"),
            games("WORLD_OF_WARCRAFT", "DIABLO_3", "DESTINY_2", "MONSTER_HUNTER", "DRAGON_QUEST", "WARFRAME", "HEARTHSTONE",
                    "DEAD_BY_DAYLIGHT", "THE_DOORS", "GTA", "BATTLEFIELD"));

    private Passion passion(Persona primary, Persona secondary) {
        HashSet<Passion.miscellaneous> misc = new HashSet<>();
        int wanted = 3 + random.nextInt(4); // 3..6
        List<Passion.miscellaneous> others = Arrays.stream(Passion.miscellaneous.values()).filter(m -> !NOT_GENERATED.contains(m)).toList();
        while (misc.size() < wanted) {
            double r = random.nextDouble();
            List<Passion.miscellaneous> pool = r < 0.55 ? PERSONA_PASSIONS.get(primary)
                    : r < 0.85 && secondary != null ? PERSONA_PASSIONS.get(secondary) : others;
            misc.add(pick(pool));
        }
        HashSet<Passion.video_games> games = new HashSet<>();
        boolean gamer = primary == Persona.GAMER || secondary == Persona.GAMER;
        int gameCount = gamer ? 3 + random.nextInt(3) : 1 + random.nextInt(2);
        List<Passion.video_games> family = gamer ? pick(GAME_FAMILIES) : GAME_FAMILIES.get(1 + random.nextInt(2)); // casual: sandbox or party
        while (games.size() < gameCount) {
            games.add(pick(random.nextDouble() < 0.75 ? family : pick(GAME_FAMILIES)));
        }
        return new Passion(games, misc);
    }

    private Passion passions(LifeStyle.athlete athlete) {
        Persona primary = athlete == LifeStyle.athlete.SPORTY && random.nextDouble() < 0.6 ? Persona.SPORTY : pick(Persona.values());
        Persona secondary = random.nextDouble() < 0.6 ? pick(Persona.values()) : null;
        return passion(primary, secondary == primary ? null : secondary);
    }

    // ================================================================== preferences

    Preferences preferences(Profile self) {
        Identity id = self.getIdentity();
        LifeStyle life = self.getLifeStyle();
        Preferences p = new Preferences();

        // Orientation: 88% heterosexual, 8% homosexual, 4% both
        double orientation = random.nextDouble();
        Biology.sex other = id.getBsex() == Biology.sex.MALE ? Biology.sex.FEMALE : Biology.sex.MALE;
        Set<Biology.sex> sexes = orientation < 0.88 ? EnumSet.of(other)
                : orientation < 0.96 ? EnumSet.of(id.getBsex()) : EnumSet.allOf(Biology.sex.class);
        p.setSexes(sexes);

        // Age: a range around the person's own age (men slightly younger, women slightly older on average)
        int shift = sexes.size() == 1 && !sexes.contains(id.getBsex()) ? (id.getBsex() == Biology.sex.MALE ? -2 : 2) : 0;
        int minAge = Math.max(18, id.getAge() + shift - (2 + random.nextInt(7)));
        int maxAge = Math.min(99, id.getAge() + shift + (2 + random.nextInt(7)));
        p.setAge(new RangeCriterion(Math.min(minAge, maxAge), Math.max(minAge, maxAge),
                weighted(new Importance[]{Importance.NICE_TO_HAVE, Importance.IMPORTANT, Importance.REQUIRED}, 15, 50, 35)));

        // Size: around the typical height of the preferred sex
        int typical = sexes.size() == 2 ? 171 : sexes.contains(Biology.sex.MALE) ? 178 : 165;
        if (sexes.size() == 1 && !sexes.contains(id.getBsex())) {
            typical += id.getBsex() == Biology.sex.FEMALE ? 3 : -3;
        }
        Importance sizeImportance = weighted(new Importance[]{Importance.INDIFFERENT, Importance.NICE_TO_HAVE, Importance.IMPORTANT}, 40, 45, 15);
        if (sizeImportance != Importance.INDIFFERENT) {
            p.setSize(new RangeCriterion(typical - (6 + random.nextInt(9)), typical + (6 + random.nextInt(9)), sizeImportance));
        }

        // IQ: most people do not care
        if (random.nextDouble() < 0.3) {
            p.setIq(new RangeCriterion(Math.max(60, id.getQi() - 15), Math.min(160, id.getQi() + 20),
                    random.nextDouble() < 0.7 ? Importance.NICE_TO_HAVE : Importance.IMPORTANT));
        }

        // Smoker: non-smokers often avoid smokers, smokers rarely care
        switch (life.getLSsmoker()) {
            case NEVER -> {
                double r = random.nextDouble();
                if (r < 0.75) {
                    Importance importance = r < 0.25 ? Importance.REQUIRED : r < 0.55 ? Importance.IMPORTANT : Importance.NICE_TO_HAVE;
                    p.setSmoker(choice(LifeStyle.smoker.class, random.nextBoolean() ? List.of(LifeStyle.smoker.NEVER)
                            : List.of(LifeStyle.smoker.NEVER, LifeStyle.smoker.OCCASIONNALY), importance));
                }
            }
            case OCCASIONNALY -> {
                if (random.nextDouble() < 0.4) {
                    p.setSmoker(choice(LifeStyle.smoker.class, List.of(LifeStyle.smoker.NEVER, LifeStyle.smoker.OCCASIONNALY,
                            LifeStyle.smoker.REGULARLY), Importance.NICE_TO_HAVE));
                }
            }
            default -> {
                if (random.nextDouble() < 0.2) {
                    p.setSmoker(choice(LifeStyle.smoker.class, List.of(LifeStyle.smoker.REGULARLY, LifeStyle.smoker.DAILY), Importance.NICE_TO_HAVE));
                }
            }
        }

        // Alcohol: own level +/- 1
        double alcohol = random.nextDouble();
        if (alcohol < 0.6) {
            p.setAlcohol(choice(LifeStyle.alcohol.class, neighbours(LifeStyle.alcohol.values(), life.getLSalcohol()),
                    alcohol < 0.5 ? Importance.NICE_TO_HAVE : Importance.IMPORTANT));
        }

        // Sport and body build
        if (life.getLSathlete() == LifeStyle.athlete.SPORTY && random.nextDouble() < 0.55) {
            p.setAthlete(choice(LifeStyle.athlete.class, List.of(LifeStyle.athlete.SPORTY),
                    random.nextBoolean() ? Importance.IMPORTANT : Importance.NICE_TO_HAVE));
        } else if (random.nextDouble() < 0.25) {
            p.setAthlete(choice(LifeStyle.athlete.class, neighbours(LifeStyle.athlete.values(), life.getLSathlete()), Importance.NICE_TO_HAVE));
        }
        if (random.nextDouble() < 0.3) {
            p.setBodyBuild(choice(LifeStyle.bodyBuild.class, neighbours(LifeStyle.bodyBuild.values(), self.getLifeStyle().getLSbodyBuild()),
                    Importance.NICE_TO_HAVE));
        }

        // Food: vegans and vegetarians often prefer someone close to their diet
        switch (life.getLSfeed()) {
            case VEGAN -> p.setFeed(choice(LifeStyle.feed.class, List.of(LifeStyle.feed.VEGAN, LifeStyle.feed.VEGETARIAN),
                    random.nextDouble() < 0.25 ? Importance.REQUIRED : Importance.IMPORTANT));
            case VEGETARIAN -> {
                if (random.nextDouble() < 0.6) {
                    p.setFeed(choice(LifeStyle.feed.class, List.of(LifeStyle.feed.VEGAN, LifeStyle.feed.VEGETARIAN, LifeStyle.feed.FLEXIVORE),
                            random.nextBoolean() ? Importance.IMPORTANT : Importance.NICE_TO_HAVE));
                }
            }
            default -> {
                if (random.nextDouble() < 0.15) {
                    p.setFeed(choice(LifeStyle.feed.class, List.of(life.getLSfeed()), Importance.NICE_TO_HAVE));
                }
            }
        }

        // Religion: believers sometimes want someone of the same religion
        LifeStyle.religion religion = life.getLSreligion();
        if (religion != LifeStyle.religion.ATHEIST && religion != LifeStyle.religion.OTHER) {
            double r = random.nextDouble();
            if (r < 0.45) {
                p.setReligion(choice(LifeStyle.religion.class, List.of(religion),
                        r < 0.15 ? Importance.REQUIRED : r < 0.35 ? Importance.IMPORTANT : Importance.NICE_TO_HAVE));
            }
        } else if (random.nextDouble() < 0.2) {
            p.setReligion(choice(LifeStyle.religion.class, List.of(LifeStyle.religion.ATHEIST, LifeStyle.religion.OTHER), Importance.NICE_TO_HAVE));
        }

        // Physical details: mostly indifferent
        if (random.nextDouble() < 0.25) {
            p.setHairColor(choice(PhysicalAttributes.hairColor.class, distinct(PhysicalAttributes.hairColor.values(), 1 + random.nextInt(2)), Importance.NICE_TO_HAVE));
        }
        if (random.nextDouble() < 0.15) {
            p.setHairType(choice(PhysicalAttributes.hairType.class, distinct(PhysicalAttributes.hairType.values(), 1 + random.nextInt(2)), Importance.NICE_TO_HAVE));
        }
        if (random.nextDouble() < 0.2) {
            p.setHairLength(choice(PhysicalAttributes.hairLength.class, distinct(PhysicalAttributes.hairLength.values(), 1 + random.nextInt(2)), Importance.NICE_TO_HAVE));
        }
        if (random.nextDouble() < 0.1) {
            p.setEthnicity(choice(Biology.ethnicity.class, List.of(id.getBethnicity()), Importance.NICE_TO_HAVE));
        }
        return p;
    }

    // ================================================================== match history

    /**
     * About 20% of the generated people get one to three past matches with compatible people,
     * dated in the 45 days before the reference date; some matches have votes.
     */
    int addMatchHistory(List<Profile> generated, Matcher matcher) {
        int created = 0;
        for (Profile profile : generated) {
            if (random.nextDouble() >= 0.2) {
                continue;
            }
            int wanted = 1 + random.nextInt(3);
            Map<TupleHistoHashMap, Date> history = profile.getModelHisto().getStockHisto();
            List<Matcher.Suggestion> suggestions = matcher.suggestions(profile, generated, wanted,
                    c -> history.containsKey(new TupleHistoHashMap(c.getIdentity().getNoId())));
            for (Matcher.Suggestion suggestion : suggestions) {
                Date date = Date.from(referenceDate.minusDays(1 + random.nextInt(45))
                        .atTime(9 + random.nextInt(12), random.nextInt(60)).atZone(ZoneId.systemDefault()).toInstant());
                Profile other = suggestion.candidate();
                history.put(vote(other, suggestion.selectedSatisfaction()), date);
                other.getModelHisto().getStockHisto().put(vote(profile, suggestion.candidateSatisfaction()), date);
                created++;
            }
        }
        return created;
    }

    /** 60% of the people voted after the meeting; the happier they were with the profile, the more positive. */
    private TupleHistoHashMap vote(Profile about, double satisfaction) {
        TupleHistoHashMap tuple = new TupleHistoHashMap(about.getIdentity().getNoId());
        if (random.nextDouble() < 0.6) {
            tuple.setVoted(true);
            tuple.setVote(random.nextDouble() < satisfaction ? 1 : 2);
        }
        return tuple;
    }

    // ================================================================== helpers

    private int normal(double mean, double standardDeviation) {
        return (int) Math.round(mean + standardDeviation * random.nextGaussian());
    }

    private static int clamp(int value, int min, int max) {
        return Math.max(min, Math.min(max, value));
    }

    private <T> T pick(T[] values) {
        return values[random.nextInt(values.length)];
    }

    private <T> T pick(List<T> values) {
        return values.get(random.nextInt(values.size()));
    }

    /** Picks values[i] with probability weights[i] / sum(weights). */
    private <T> T weighted(T[] values, int... weights) {
        if (values.length != weights.length) {
            throw new IllegalArgumentException(values.length + " values but " + weights.length + " weights");
        }
        int r = random.nextInt(Arrays.stream(weights).sum());
        for (int i = 0; i < values.length; i++) {
            r -= weights[i];
            if (r < 0) {
                return values[i];
            }
        }
        throw new AssertionError();
    }

    private static <E extends Enum<E>> List<E> neighbours(E[] values, E value) {
        List<E> result = new ArrayList<>();
        for (int i = Math.max(0, value.ordinal() - 1); i <= Math.min(values.length - 1, value.ordinal() + 1); i++) {
            result.add(values[i]);
        }
        return result;
    }

    private <E> List<E> distinct(E[] values, int count) {
        List<E> shuffled = new ArrayList<>(Arrays.asList(values));
        Collections.shuffle(shuffled, random);
        return shuffled.subList(0, Math.min(count, shuffled.size()));
    }

    private static <E extends Enum<E>> ChoiceCriterion<E> choice(Class<E> type, List<E> accepted, Importance importance) {
        return new ChoiceCriterion<>(type, accepted, importance);
    }

    private static List<Passion.miscellaneous> misc(String... names) {
        return Arrays.stream(names).map(Passion.miscellaneous::valueOf).toList();
    }

    private static List<Passion.video_games> games(String... names) {
        return Arrays.stream(names).map(Passion.video_games::valueOf).toList();
    }
}
